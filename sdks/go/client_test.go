var uuidV4Re = regexp.MustCompile(`^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$`)

func TestNormalizeBaseURL(t *testing.T) {
	tests := []struct {
		in      string
		want    string
		wantErr bool
	}{
		{"", "https://api.kibo.to/v1", false},
		{"https://api.kibo.to", "https://api.kibo.to/v1", false},
		{"https://api.kibo.to/", "https://api.kibo.to/v1", false},
		{"https://api.kibo.to/v1", "https://api.kibo.to/v1", false},
		{"https://api.kibo.to/v1/", "https://api.kibo.to/v1", false},
		{"http://127.0.0.1:8080/proxy", "http://127.0.0.1:8080/proxy/v1", false},
		{"http://127.0.0.1:8080/proxy/v1/", "http://127.0.0.1:8080/proxy/v1", false},
		{"ftp://api.kibo.to", "", true},
		{"https://", "", true},
	}

	for _, tc := range tests {
		got, err := kibotos.NormalizeBaseURL(tc.in)
		if tc.wantErr {
			if err == nil {
				t.Errorf("NormalizeBaseURL(%q) = %q, want error", tc.in, got)
			}
			continue
		}
		if err != nil {
			t.Errorf("NormalizeBaseURL(%q) unexpected error: %v", tc.in, err)
			continue
		}
		if got != tc.want {
			t.Errorf("NormalizeBaseURL(%q) = %q, want %q", tc.in, got, tc.want)
		}
	}
}

func TestNewClientAndEnv(t *testing.T) {
	if _, err := kibotos.NewClient(""); err == nil {
		t.Fatal("expected error for empty api key")
	}

	t.Setenv("KIBOTOS_API_KEY", "")
	t.Setenv("KIBOTOS_API_URL", "")
	if _, err := kibotos.NewClientFromEnv(); err == nil {
		t.Fatal("expected error when KIBOTOS_API_KEY is unset")
	}

	t.Setenv("KIBOTOS_API_KEY", "kb_testkey")
	t.Setenv("KIBOTOS_API_URL", "https://staging.kibo.to")
	c, err := kibotos.NewClientFromEnv()
	if err != nil {
		t.Fatalf("NewClientFromEnv: %v", err)
	}
	if c.BaseURL() != "https://staging.kibo.to/v1" {
		t.Fatalf("BaseURL = %q, want https://staging.kibo.to/v1", c.BaseURL())
	}

	// Explicit option overrides env URL.
	c2, err := kibotos.NewClientFromEnv(kibotos.WithBaseURL("http://localhost:9000/v1/"))
	if err != nil {
		t.Fatalf("NewClientFromEnv override: %v", err)
	}
	if c2.BaseURL() != "http://localhost:9000/v1" {
		t.Fatalf("BaseURL override = %q, want http://localhost:9000/v1", c2.BaseURL())
	}
}

func TestIdempotencyKeyAutoGeneratedAndReusedOnRetry(t *testing.T) {
	var attempts atomic.Int32
	var keys []string

	srv := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		if r.Header.Get("Authorization") != "Bearer kb_secret" {
			t.Errorf("unexpected Authorization: %q", r.Header.Get("Authorization"))
		}
		if r.Header.Get("User-Agent") != "custom-agent/1.0" {
			t.Errorf("unexpected User-Agent: %q", r.Header.Get("User-Agent"))
		}
		if r.Header.Get("X-Custom") != "hello" {
			t.Errorf("unexpected X-Custom: %q", r.Header.Get("X-Custom"))
		}

		keys = append(keys, r.Header.Get("Idempotency-Key"))
		n := attempts.Add(1)
		w.Header().Set("Content-Type", "application/json")
		w.Header().Set("Request-Id", "req_retry")
		if n < 3 {
			w.WriteHeader(http.StatusServiceUnavailable)
			_, _ = w.Write([]byte(`{"error":{"code":"capacity_unavailable","message":"try again","status":503,"request_id":"req_retry","retryable":true}}`))
			return
		}
		w.WriteHeader(http.StatusAccepted)
		_, _ = w.Write([]byte(`{"id":"wks_123","status":"creating"}`))
	}))
	defer srv.Close()

	c, err := kibotos.NewClient("kb_secret",
		kibotos.WithBaseURL(srv.URL),
		kibotos.WithUserAgent("custom-agent/1.0"),
		kibotos.WithMaxRetries(3),
		kibotos.WithRetryBackoff(time.Millisecond, 2*time.Millisecond),
	)
	if err != nil {
		t.Fatalf("NewClient: %v", err)
	}

	ws, err := c.Workspaces.Create(context.Background(), kibotos.CreateWorkspaceParams{
		Template: kibotos.WorkspaceTemplateSpec{ID: "python-3.12"},
	}, kibotos.WithHeader("X-Custom", "hello"))
	if err != nil {
		t.Fatalf("Create failed: %v", err)
	}
	if ws.ID != "wks_123" {
		t.Fatalf("ws.ID = %q, want wks_123", ws.ID)
	}
	if len(keys) != 3 {
		t.Fatalf("got %d attempts, want 3", len(keys))
	}
	if !uuidV4Re.MatchString(keys[0]) {
		t.Fatalf("expected UUID v4 Idempotency-Key, got %q", keys[0])
	}
	if keys[0] != keys[1] || keys[1] != keys[2] {
		t.Fatalf("expected identical Idempotency-Key across retries, got %v", keys)
	}
}

func TestExplicitIdempotencyKeyAndRetryAfter(t *testing.T) {
	var attempts atomic.Int32
	srv := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		if r.Header.Get("Idempotency-Key") != "my-explicit-key" {
			t.Errorf("Idempotency-Key = %q, want my-explicit-key", r.Header.Get("Idempotency-Key"))
		}
		n := attempts.Add(1)
		w.Header().Set("Content-Type", "application/json")
		if n == 1 {
			w.Header().Set("Retry-After", "0.02")
			w.WriteHeader(http.StatusTooManyRequests)
			_, _ = w.Write([]byte(`{"error":{"code":"rate_limited","message":"slow down","status":429,"request_id":"req_429","retryable":true}}`))
			return
		}
		w.WriteHeader(http.StatusAccepted)
		_, _ = w.Write([]byte(`{"id":"vol_1","size_gib":10,"status":"creating"}`))
	}))
	defer srv.Close()

	c, err := kibotos.NewClient("kb_secret",
		kibotos.WithBaseURL(srv.URL),
		kibotos.WithMaxRetries(2),
		kibotos.WithRetryBackoff(time.Millisecond, 5*time.Millisecond),
	)
	if err != nil {
		t.Fatalf("NewClient: %v", err)
	}

	start := time.Now()
	vol, err := c.Volumes.Create(context.Background(), kibotos.CreateVolumeParams{
		SizeGiB: 10,
	}, kibotos.WithIdempotencyKey("my-explicit-key"))
	if err != nil {
		t.Fatalf("Create: %v", err)
	}
	elapsed := time.Since(start)
	if elapsed < 15*time.Millisecond {
		t.Fatalf("expected Retry-After delay >= 15ms, got %v", elapsed)
	}
	if vol.ID != "vol_1" {
		t.Fatalf("vol.ID = %q, want vol_1", vol.ID)
	}
}

func TestRetryOnRetryable409AndNoRetryOnNonRetryable(t *testing.T) {
	var retryableAttempts atomic.Int32
	var nonRetryableAttempts atomic.Int32

	srv := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		w.Header().Set("Content-Type", "application/json")
		switch r.URL.Path {
		case "/v1/workspaces/wks_busy/start":
			n := retryableAttempts.Add(1)
			if n == 1 {
				w.WriteHeader(http.StatusConflict)
				_, _ = w.Write([]byte(`{"error":{"code":"operation_in_progress","message":"busy","status":409,"request_id":"req_1","retryable":true}}`))
				return
			}
			w.WriteHeader(http.StatusAccepted)
			_, _ = w.Write([]byte(`{"id":"wks_busy","status":"starting"}`))
		case "/v1/workspaces/wks_bad/start":
			nonRetryableAttempts.Add(1)
			w.WriteHeader(http.StatusConflict)
			_, _ = w.Write([]byte(`{"error":{"code":"invalid_state","message":"already available","status":409,"request_id":"req_2","retryable":false,"details":{"current":"available"}}}`))
		}
	}))
	defer srv.Close()

	c, err := kibotos.NewClient("kb_secret",
		kibotos.WithBaseURL(srv.URL),
		kibotos.WithMaxRetries(3),
		kibotos.WithRetryBackoff(time.Millisecond, 2*time.Millisecond),
	)
	if err != nil {
		t.Fatalf("NewClient: %v", err)
	}

	ws, err := c.Workspaces.Start(context.Background(), "wks_busy", nil)
	if err != nil {
		t.Fatalf("Start wks_busy: %v", err)
	}
	if ws.Status != kibotos.WorkspaceStatusStarting || retryableAttempts.Load() != 2 {
		t.Fatalf("got status=%q attempts=%d, want starting/2", ws.Status, retryableAttempts.Load())
	}

	_, err = c.Workspaces.Start(context.Background(), "wks_bad", nil)
	if err == nil {
		t.Fatal("expected error for wks_bad")
	}
	if nonRetryableAttempts.Load() != 1 {
		t.Fatalf("expected 1 attempt for non-retryable 409, got %d", nonRetryableAttempts.Load())
	}
	var apiErr *kibotos.APIError
	if !errors.As(err, &apiErr) {
		t.Fatalf("expected *APIError, got %T", err)
	}
	if apiErr.Code != "invalid_state" || apiErr.RequestID != "req_2" || apiErr.Details["current"] != "available" {
		t.Fatalf("unexpected APIError: %+v", apiErr)
	}
	if kibotos.IsRetryable(err) {
		t.Fatal("expected IsRetryable == false")
	}
}

type flakyTransport struct {
	failures atomic.Int32
	inner    http.RoundTripper
}

func (f *flakyTransport) RoundTrip(req *http.Request) (*http.Response, error) {
	if f.failures.Add(1) <= 1 {
		return nil, io.ErrUnexpectedEOF
	}
	return f.inner.RoundTrip(req)
}

func TestRetryOnTransientNetworkError(t *testing.T) {
	srv := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		w.Header().Set("Content-Type", "application/json")
		_, _ = w.Write([]byte(`{"data":[],"next_page_token":null}`))
	}))
	defer srv.Close()

	tr := &flakyTransport{inner: srv.Client().Transport}
	c, err := kibotos.NewClient("kb_secret",
		kibotos.WithBaseURL(srv.URL),
		kibotos.WithHTTPClient(&http.Client{Transport: tr}),
		kibotos.WithMaxRetries(2),
		kibotos.WithRetryBackoff(time.Millisecond, 2*time.Millisecond),
	)
	if err != nil {
		t.Fatalf("NewClient: %v", err)
	}

	page, err := c.Zones.List(context.Background(), nil)
	if err != nil {
		t.Fatalf("Zones.List failed after network retry: %v", err)
	}
	if len(page.Data) != 0 || tr.failures.Load() != 2 {
		t.Fatalf("expected 2 transport calls, got %d", tr.failures.Load())
	}
}

func TestContextCancellationDuringRetryBackoff(t *testing.T) {
	srv := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		w.Header().Set("Retry-After", "60")
		w.WriteHeader(http.StatusTooManyRequests)
		_, _ = w.Write([]byte(`{"error":{"code":"rate_limited","message":"wait","status":429,"retryable":true}}`))
	}))
	defer srv.Close()

	c, err := kibotos.NewClient("kb_secret",
		kibotos.WithBaseURL(srv.URL),
		kibotos.WithMaxRetries(3),
	)
	if err != nil {
		t.Fatalf("NewClient: %v", err)
	}

	ctx, cancel := context.WithTimeout(context.Background(), 40*time.Millisecond)
	defer cancel()

	start := time.Now()
	_, err = c.Zones.List(ctx, nil)
	if !errors.Is(err, context.DeadlineExceeded) {
		t.Fatalf("expected context.DeadlineExceeded, got %v", err)
	}
	if time.Since(start) > time.Second {
		t.Fatalf("cancellation took too long: %v", time.Since(start))
	}
}

func TestErrorHelpersAndFallbackParsing(t *testing.T) {
	srv := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		w.Header().Set("Request-Id", "req_hdr_123")
		switch r.URL.Path {
		case "/v1/workspaces/missing":
			w.Header().Set("Content-Type", "application/json")
			w.WriteHeader(http.StatusNotFound)
			_ = json.NewEncoder(w).Encode(map[string]any{
				"error": map[string]any{
					"code":      "workspace_not_found",
					"message":   "not here",
					"status":    404,
					"retryable": false,
				},
			})
		case "/v1/workspaces/rate":
			w.WriteHeader(http.StatusTooManyRequests)
			_, _ = w.Write([]byte("plain text rate limit"))
		case "/v1/workspaces/unauth":
			w.WriteHeader(http.StatusUnauthorized)
			_, _ = w.Write([]byte(`{"error":{"code":"unauthenticated","message":"bad key","status":401,"retryable":false}}`))
		}
	}))
	defer srv.Close()

	c, err := kibotos.NewClient("kb_secret",
		kibotos.WithBaseURL(srv.URL),
		kibotos.WithMaxRetries(0),
	)
	if err != nil {
		t.Fatalf("NewClient: %v", err)
	}

	_, err = c.Workspaces.Get(context.Background(), "missing")
	if !kibotos.IsNotFound(err) {
		t.Fatalf("expected IsNotFound, got %v", err)
	}
	var apiErr *kibotos.APIError
	if !errors.As(err, &apiErr) || apiErr.RequestID != "req_hdr_123" {
		t.Fatalf("expected Request-Id header fallback, got %+v", apiErr)
	}
	if !strings.Contains(apiErr.Error(), "workspace_not_found") {
		t.Fatalf("unexpected Error() string: %q", apiErr.Error())
	}

	_, err = c.Workspaces.Get(context.Background(), "rate")
	if !kibotos.IsRateLimited(err) || !kibotos.IsRetryable(err) {
		t.Fatalf("expected IsRateLimited && IsRetryable, got %v", err)
	}

	_, err = c.Workspaces.Get(context.Background(), "unauth")
	if !kibotos.IsUnauthenticated(err) {
		t.Fatalf("expected IsUnauthenticated, got %v", err)
	}
}

func TestRetryAfterHTTPDate(t *testing.T) {
	var attempts atomic.Int32
	srv := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		if attempts.Add(1) == 1 {
			// Past HTTP-date should be clamped to 0 delay and retried immediately.
			w.Header().Set("Retry-After", time.Now().Add(-time.Second).UTC().Format(http.TimeFormat))
			w.WriteHeader(http.StatusTooManyRequests)
			_, _ = w.Write([]byte(`{"error":{"code":"rate_limited","message":"limit","status":429,"retryable":true}}`))
			return
		}
		w.Header().Set("Content-Type", "application/json")
		_, _ = w.Write([]byte(`{"data":[],"next_page_token":null}`))
	}))
	defer srv.Close()

	c, err := kibotos.NewClient("kb_test",
		kibotos.WithBaseURL(srv.URL),
		kibotos.WithMaxRetries(2),
	)
	if err != nil {
		t.Fatalf("NewClient: %v", err)
	}
	if _, err := c.Zones.List(context.Background(), nil); err != nil {
		t.Fatalf("Zones.List: %v", err)
	}
	if attempts.Load() != 2 {
		t.Fatalf("attempts = %d, want 2", attempts.Load())
	}
}
